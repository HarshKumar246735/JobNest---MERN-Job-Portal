const express = require('express');
const helmet = require('helmet');
const cors = require('cors');
const cookieParser = require('cookie-parser');
const rateLimit = require('express-rate-limit');
const sanitize = require('./utils/sanitize');
const errorHandler = require('./middleware/error');
const app = express();
app.use(helmet());
app.use(cors({ origin: (process.env.CLIENT_URL || 'http://localhost:5173').split(','), credentials: true }));
app.use(express.json({ limit: '1mb' }));
app.use(cookieParser());
app.use(sanitize);
app.use('/api', rateLimit({ windowMs: 15 * 60 * 1000, limit: 300 }));
app.use('/api/auth', rateLimit({ windowMs: 15 * 60 * 1000, limit: 30 }));
app.get('/api/health', (_q, r) => r.json({ ok: true }));
app.use('/api/auth', require('./routes/auth'));
app.set('trust proxy', 1);
app.use('/uploads/logos', express.static(require('path').join(__dirname, 'uploads/logos'), { setHeaders: (r) => r.setHeader('Cross-Origin-Resource-Policy', 'cross-origin') })); // logos are public; resumes are never served statically
app.use('/', require('./routes/seo'));
app.use('/api/resumes', require('./routes/resumeAccess'));
app.use('/api/admin', require('./routes/admin'));
app.use('/api/reports', require('./routes/reports'));
app.use('/api', require('./routes/candidate'));
app.use('/api', require('./routes/recruiter'));
app.use('/api', require('./routes/public'));
app.use((_q, r) => r.status(404).json({ success: false, message: 'Route not found' }));
app.use(errorHandler);
module.exports = app;
